-- Tablas de datos procesados de AgroResilience. Generado con: scripts/cargar_supabase.py --esquema
-- Los crudos no viven en la base: cada carga entra por una tabla temporal y solo queda lo procesado.

create table if not exists public.puntos (
  id smallint generated by default as identity primary key,
  codigo text not null unique,
  nombre text,
  latitud double precision not null,
  longitud double precision not null,
  departamento text,
  tipo text,
  cultivos_zona text
);

-- Por donde va cada tabla: la carga diaria lee de aqui la ultima fecha, sin recorrer las series.
create table if not exists public.cargas (
  tabla text primary key,
  ultima_fecha date,
  filas bigint not null default 0,
  enviadas integer not null default 0,
  cambiadas integer not null default 0,
  actualizado timestamptz not null default now()
);

create table if not exists public.power_diario_largo (
  punto_id smallint not null references public.puntos (id),
  fecha date not null,
